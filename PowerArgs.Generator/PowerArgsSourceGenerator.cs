using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PowerArgs.Generator
{
    [Generator]
    public sealed class PowerArgsSourceGenerator : IIncrementalGenerator
    {
        private static readonly SymbolDisplayFormat TypeFormat = new SymbolDisplayFormat(
            globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Included,
            typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
            genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
            miscellaneousOptions: SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var partialProperties = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is PropertyDeclarationSyntax property && property.Modifiers.Any(SyntaxKind.PartialKeyword),
                static (syntaxContext, _) => syntaxContext.SemanticModel.GetDeclaredSymbol((PropertyDeclarationSyntax)syntaxContext.Node) as IPropertySymbol)
                .Where(static property => property != null && property.PartialDefinitionPart == null && property.PartialImplementationPart == null);

            context.RegisterSourceOutput(partialProperties.Collect(), static (productionContext, properties) => Generate(productionContext, properties));
        }

        private static void Generate(SourceProductionContext context, ImmutableArray<IPropertySymbol?> discoveredProperties)
        {
            var models = new Dictionary<INamedTypeSymbol, List<IPropertySymbol>>(SymbolEqualityComparer.Default);
            foreach (var property in discoveredProperties)
            {
                if (property == null || property.ContainingType.TypeKind != TypeKind.Class || property.ContainingType.TypeParameters.Length != 0) continue;
                if (CanReopen(property.ContainingType) == false) continue;

                if (models.TryGetValue(property.ContainingType, out var properties) == false)
                {
                    properties = new List<IPropertySymbol>();
                    models.Add(property.ContainingType, properties);
                }
                if (properties.Any(existing => SymbolEqualityComparer.Default.Equals(existing, property)) == false) properties.Add(property);
            }

            foreach (var pair in models)
            {
                pair.Value.Sort((left, right) => left.Locations.First().SourceSpan.Start.CompareTo(right.Locations.First().SourceSpan.Start));
                context.AddSource(MakeHintName(pair.Key), SourceText.From(GenerateModel(pair.Key, pair.Value), Encoding.UTF8));
            }
        }

        private static bool CanReopen(INamedTypeSymbol type)
        {
            for (var current = type; current != null; current = current.ContainingType)
            {
                if (current.TypeParameters.Length != 0) return false;
                if (current.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax() is TypeDeclarationSyntax declaration && declaration.Modifiers.Any(SyntaxKind.PartialKeyword)) == false) return false;
            }
            return true;
        }

        private static string GenerateModel(INamedTypeSymbol type, List<IPropertySymbol> partialProperties)
        {
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("#nullable enable");

            if (type.ContainingNamespace.IsGlobalNamespace == false)
            {
                source.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
                source.AppendLine();
            }

            var containingTypes = GetContainingTypes(type);
            for (var i = 0; i < containingTypes.Count; i++)
            {
                source.Append(' ', i * 4).Append(GetAccessibility(containingTypes[i].DeclaredAccessibility)).Append(" partial class ").Append(Escape(containingTypes[i].Name)).AppendLine();
                source.Append(' ', i * 4).AppendLine("{");
            }

            var bodyIndent = new string(' ', containingTypes.Count * 4);
            for (var i = 0; i < partialProperties.Count; i++)
            {
                AppendPropertyImplementation(source, bodyIndent, partialProperties[i], i);
            }

            if (CanGenerateFastPath(type, partialProperties, out var argumentProperties))
            {
                AppendFastPath(source, bodyIndent, type, argumentProperties);
            }

            for (var i = containingTypes.Count - 1; i >= 0; i--)
            {
                source.Append(' ', i * 4).AppendLine("}");
            }

            return source.ToString();
        }

        private static List<INamedTypeSymbol> GetContainingTypes(INamedTypeSymbol type)
        {
            var result = new List<INamedTypeSymbol>();
            for (var current = type; current != null; current = current.ContainingType) result.Add(current);
            result.Reverse();
            return result;
        }

        private static void AppendPropertyImplementation(StringBuilder source, string indent, IPropertySymbol property, int propertyIndex)
        {
            var fieldName = "__powerArgsGeneratedValue" + propertyIndex;
            var propertyType = property.Type.ToDisplayString(TypeFormat);
            var staticText = property.IsStatic ? "static " : string.Empty;
            source.Append(indent).Append("private ").Append(staticText).Append(propertyType).Append(' ').Append(fieldName).AppendLine(" = default!;");
            source.Append(indent).Append(GetAccessibility(property.DeclaredAccessibility)).Append(' ').Append(staticText).Append("partial ").Append(propertyType).Append(' ').Append(Escape(property.Name)).AppendLine();
            source.Append(indent).AppendLine("{");
            if (property.GetMethod != null)
            {
                source.Append(indent).Append("    ").Append(GetAccessorAccessibility(property, property.GetMethod)).Append("get => ").Append(fieldName).AppendLine(";");
            }
            if (property.SetMethod != null)
            {
                source.Append(indent).Append("    ").Append(GetAccessorAccessibility(property, property.SetMethod)).Append(property.SetMethod.IsInitOnly ? "init" : "set").Append(" => ").Append(fieldName).AppendLine(" = value;");
            }
            source.Append(indent).AppendLine("}");
            source.AppendLine();
        }

        private static string GetAccessorAccessibility(IPropertySymbol property, IMethodSymbol accessor)
        {
            return accessor.DeclaredAccessibility == property.DeclaredAccessibility ? string.Empty : GetAccessibility(accessor.DeclaredAccessibility) + " ";
        }

        private static bool CanGenerateFastPath(INamedTypeSymbol type, List<IPropertySymbol> partialProperties, out List<IPropertySymbol> argumentProperties)
        {
            var publicProperties = type.GetMembers().OfType<IPropertySymbol>()
                .Where(property => property.IsStatic == false && property.DeclaredAccessibility == Accessibility.Public && property.IsIndexer == false)
                .OrderBy(property => property.Locations.FirstOrDefault()?.SourceSpan.Start ?? int.MaxValue)
                .ToList();

            argumentProperties = new List<IPropertySymbol>();
            if (type.IsAbstract || publicProperties.Count == 0) return false;
            if (type.BaseType?.SpecialType != SpecialType.System_Object) return false;
            if (type.InstanceConstructors.Any(constructor => constructor.Parameters.Length == 0) == false) return false;
            if (type.GetAttributes().Any(attribute => IsPowerArgsAttribute(attribute) && IsSupportedTypeAttribute(attribute) == false)) return false;
            if (type.GetAttributes().Count(IsCaseAttribute) > 1) return false;
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>().Where(method => method.MethodKind == MethodKind.Ordinary && method.IsImplicitlyDeclared == false))
            {
                if (method.Name == "Main") continue;
                if (method.GetAttributes().Any(IsArgActionMethod) == false) return false;
                if (method.ReturnsVoid == false && IsTask(method.ReturnType) == false) return false;
                if (method.GetAttributes().Any(attribute => IsPowerArgsAttribute(attribute) && IsSupportedActionAttribute(attribute) == false)) return false;
                if (method.GetAttributes().Count(IsCaseAttribute) > 1) return false;
                if (CanGenerateAction(method, type) == false) return false;
            }

            foreach (var property in publicProperties)
            {
                if (partialProperties.Any(candidate => SymbolEqualityComparer.Default.Equals(candidate, property)) == false) return false;
                if (property.GetMethod == null || property.SetMethod == null || property.SetMethod.IsInitOnly || property.GetMethod.DeclaredAccessibility != Accessibility.Public || property.SetMethod.DeclaredAccessibility != Accessibility.Public) return false;
                if (property.GetAttributes().Any(attribute => IsPowerArgsAttribute(attribute) && IsSupportedPropertyAttribute(attribute) == false)) return false;
                if (property.GetAttributes().Count(IsCaseAttribute) > 1) return false;
                if (property.GetAttributes().Any(IsArgIgnore) == false)
                {
                    if (IsDirectType(property.Type) == false || HasOnlySimpleRequiredMetadata(property.GetAttributes()) == false) return false;
                    argumentProperties.Add(property);
                }
            }

            return argumentProperties.Count > 0 || type.GetMembers().OfType<IMethodSymbol>().Any(method => method.Name == "Main" || method.GetAttributes().Any(IsArgActionMethod));
        }

        private static bool IsPowerArgsAttribute(AttributeData attribute) => attribute.AttributeClass?.ContainingNamespace.ToDisplayString() == "PowerArgs";

        private static bool IsArgRequired(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgRequired" && IsPowerArgsAttribute(attribute);

        private static bool IsArgIgnore(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgIgnoreAttribute" && IsPowerArgsAttribute(attribute);

        private static bool IsArgActionMethod(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgActionMethod" && IsPowerArgsAttribute(attribute);

        private static bool IsCaseAttribute(AttributeData attribute) => (attribute.AttributeClass?.Name == "ArgIgnoreCase" || attribute.AttributeClass?.Name == "ArgEnforceCase") && IsPowerArgsAttribute(attribute);

        private static bool IsSupportedTypeAttribute(AttributeData attribute)
        {
            var name = attribute.AttributeClass?.Name;
            return name == "ArgDescription" || name == "ArgIgnoreCase" || name == "ArgEnforceCase";
        }

        private static bool IsSupportedPropertyAttribute(AttributeData attribute)
        {
            var name = attribute.AttributeClass?.Name;
            return name == "ArgRequired" || name == "ArgShortcut" || name == "ArgDescription" || name == "ArgPosition" || name == "ArgIgnoreAttribute" || name == "ArgIgnoreCase" || name == "ArgEnforceCase" || name == "ArgRange";
        }

        private static bool IsSupportedActionAttribute(AttributeData attribute)
        {
            var name = attribute.AttributeClass?.Name;
            return name == "ArgActionMethod" || name == "ArgShortcut" || name == "ArgDescription" || name == "ArgIgnoreCase" || name == "ArgEnforceCase";
        }

        private static bool IsTask(ITypeSymbol type) => type.ToDisplayString() == "System.Threading.Tasks.Task";

        private static bool CanGenerateAction(IMethodSymbol method, INamedTypeSymbol parentType)
        {
            if (method.TypeParameters.Length != 0 || method.Parameters.Any(parameter => parameter.RefKind != RefKind.None || parameter.HasExplicitDefaultValue)) return false;
            if (method.Parameters.Length == 0) return true;
            if (method.Parameters.All(parameter => IsDirectType(parameter.Type)))
            {
                return method.Parameters.All(parameter => parameter.GetAttributes().All(attribute => IsPowerArgsAttribute(attribute) == false || IsSupportedPropertyAttribute(attribute)) && parameter.GetAttributes().Count(IsCaseAttribute) <= 1 && HasOnlySimpleRequiredMetadata(parameter.GetAttributes()));
            }
            if (method.Parameters.Length != 1 || method.Parameters[0].Type is INamedTypeSymbol == false) return false;

            var argumentType = (INamedTypeSymbol)method.Parameters[0].Type;
            if (argumentType.TypeKind != TypeKind.Class || argumentType.IsAbstract || argumentType.InstanceConstructors.Any(constructor => constructor.Parameters.Length == 0 && constructor.DeclaredAccessibility != Accessibility.Private) == false) return false;
            if (argumentType.GetAttributes().Any(attribute => IsPowerArgsAttribute(attribute) && IsSupportedTypeAttribute(attribute) == false)) return false;
            if (GetIgnoreCase(argumentType.GetAttributes(), true) != GetIgnoreCase(parentType.GetAttributes(), true)) return false;
            foreach (var property in GetActionArgumentProperties(argumentType))
            {
                if (property.GetMethod == null || property.SetMethod == null || property.SetMethod.IsInitOnly || property.GetMethod.DeclaredAccessibility != Accessibility.Public || property.SetMethod.DeclaredAccessibility != Accessibility.Public) return false;
                if (IsDirectType(property.Type) == false) return false;
                if (property.GetAttributes().Any(attribute => IsPowerArgsAttribute(attribute) && IsSupportedPropertyAttribute(attribute) == false)) return false;
                if (property.GetAttributes().Count(IsCaseAttribute) > 1) return false;
                if (HasOnlySimpleRequiredMetadata(property.GetAttributes()) == false) return false;
            }
            return true;
        }

        private static bool HasOnlySimpleRequiredMetadata(IEnumerable<AttributeData> attributes) => attributes.Where(IsArgRequired).All(attribute => attribute.NamedArguments.Length == 0 && attribute.ConstructorArguments.Length == 0);

        private static List<IPropertySymbol> GetActionArgumentProperties(INamedTypeSymbol type) => type.GetMembers().OfType<IPropertySymbol>()
            .Where(property => property.IsStatic == false && property.DeclaredAccessibility == Accessibility.Public && property.IsIndexer == false && property.GetAttributes().Any(IsArgIgnore) == false)
            .OrderBy(property => property.Locations.FirstOrDefault()?.SourceSpan.Start ?? int.MaxValue)
            .ToList();

        private static void AppendFastPath(StringBuilder source, string indent, INamedTypeSymbol type, List<IPropertySymbol> properties)
        {
            var typeName = type.ToDisplayString(TypeFormat);
            var plans = BuildArgumentPlans(type, properties);
            var actionPlans = BuildActionPlans(type);
            source.Append(indent).AppendLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            source.Append(indent).AppendLine("internal static void __RegisterPowerArgsGeneratedModel()");
            source.Append(indent).AppendLine("{");
            source.Append(indent).Append("    global::PowerArgs.GeneratedArgumentModelRegistry.Register<").Append(typeName).AppendLine(">(");
            source.Append(indent).Append("        static () => new ").Append(typeName).AppendLine("(),");
            source.Append(indent).AppendLine("        static definition =>");
            source.Append(indent).AppendLine("        {");

            foreach (var attribute in type.GetAttributes().Where(IsPowerArgsAttribute))
            {
                source.Append(indent).Append("            definition.Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
            }

            for (var i = 0; i < plans.Count; i++)
            {
                var plan = plans[i];
                var property = plan.Property;
                var variableName = "argument" + i;
                source.Append(indent).Append("            var ").Append(variableName).Append(" = global::PowerArgs.CommandLineArgument.CreateGenerated(typeof(").Append(property.Type.ToDisplayString(TypeFormat)).Append("), ").Append(plan.IncludePropertyName ? ToLiteral(property.Name) : "null").Append(", ").Append(plan.IgnoreCase ? "true" : "false").AppendLine(");");
                if (plan.AutomaticShortcut != null)
                {
                    source.Append(indent).Append("            ").Append(variableName).Append(".Aliases.Add(").Append(ToLiteral(plan.AutomaticShortcut)).AppendLine(");");
                }

                foreach (var attribute in property.GetAttributes().Where(attribute => IsPowerArgsAttribute(attribute) && IsArgIgnore(attribute) == false))
                {
                    source.Append(indent).Append("            ").Append(variableName).Append(".Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
                }
                if (plan.Position >= 0) source.Append(indent).Append("            ").Append(variableName).Append(".Position = ").Append(plan.Position).AppendLine(";");
                source.Append(indent).Append("            definition.Arguments.Add(").Append(variableName).AppendLine(");");
            }

            for (var i = 0; i < actionPlans.Count; i++)
            {
                var plan = actionPlans[i];
                var variableName = "action" + i;
                source.Append(indent).Append("            var ").Append(variableName).Append(" = global::PowerArgs.CommandLineAction.CreateGenerated(").Append(plan.IncludeMethodName ? ToLiteral(plan.Method.Name) : "null").Append(", ").Append(plan.IgnoreCase ? "true" : "false").AppendLine(");");
                foreach (var attribute in plan.Method.GetAttributes().Where(IsPowerArgsAttribute)) source.Append(indent).Append("            ").Append(variableName).Append(".Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
                for (var argumentIndex = 0; argumentIndex < plan.ArgumentProperties.Count; argumentIndex++)
                {
                    var argumentPlan = plan.ArgumentProperties[argumentIndex];
                    AppendGeneratedActionArgumentDefinition(source, indent, variableName, "actionArgument" + i + "_" + argumentIndex, argumentPlan.Property.Type, argumentPlan.Property.Name, argumentPlan.IgnoreCase, argumentPlan.Position, argumentPlan.AutomaticShortcut, argumentPlan.Property.GetAttributes());
                }
                for (var argumentIndex = 0; argumentIndex < plan.ParameterArguments.Count; argumentIndex++)
                {
                    var argumentPlan = plan.ParameterArguments[argumentIndex];
                    AppendGeneratedActionArgumentDefinition(source, indent, variableName, "actionArgument" + i + "_" + argumentIndex, argumentPlan.Parameter.Type, argumentPlan.Parameter.Name, argumentPlan.IgnoreCase, argumentPlan.Position, null, argumentPlan.Parameter.GetAttributes());
                }
                source.Append(indent).Append("            definition.Actions.Add(").Append(variableName).AppendLine(");");
            }

            source.Append(indent).AppendLine("        },");
            source.Append(indent).AppendLine("        static (instance, index, value) =>");
            source.Append(indent).AppendLine("        {");
            for (var i = 0; i < plans.Count; i++)
            {
                source.Append(indent).Append("            if (index == ").Append(i).Append(") { instance.").Append(Escape(plans[i].Property.Name)).Append(" = (").Append(plans[i].Property.Type.ToDisplayString(TypeFormat)).AppendLine(")value; return; }");
            }
            source.Append(indent).AppendLine("            throw new global::System.ArgumentOutOfRangeException(nameof(index));");
            source.Append(indent).Append("        },").AppendLine();
            AppendDirectArguments(source, indent, plans);
            source.AppendLine(",");
            AppendMainInvokers(source, indent, type, typeName);
            source.AppendLine(",");
            AppendGeneratedActions(source, indent, typeName, actionPlans);
            source.Append(indent).AppendLine("    );");
            source.Append(indent).AppendLine("}");
            source.AppendLine();
        }

        private static void AppendGeneratedActionArgumentDefinition(StringBuilder source, string indent, string actionVariable, string argumentVariable, ITypeSymbol argumentType, string argumentName, bool ignoreCase, int position, string? automaticShortcut, IEnumerable<AttributeData> attributes)
        {
            source.Append(indent).Append("            var ").Append(argumentVariable).Append(" = global::PowerArgs.CommandLineArgument.CreateGenerated(typeof(").Append(argumentType.ToDisplayString(TypeFormat)).Append("), ").Append(ToLiteral(argumentName)).Append(", ").Append(ignoreCase ? "true" : "false").AppendLine(");");
            if (automaticShortcut != null) source.Append(indent).Append("            ").Append(argumentVariable).Append(".Aliases.Add(").Append(ToLiteral(automaticShortcut)).AppendLine(");");
            foreach (var attribute in attributes.Where(attribute => IsPowerArgsAttribute(attribute) && IsArgIgnore(attribute) == false)) source.Append(indent).Append("            ").Append(argumentVariable).Append(".Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
            if (position >= 0) source.Append(indent).Append("            ").Append(argumentVariable).Append(".Position = ").Append(position).AppendLine(";");
            source.Append(indent).Append("            ").Append(actionVariable).Append(".Arguments.Add(").Append(argumentVariable).AppendLine(");");
        }

        private static void AppendMainInvokers(StringBuilder source, string indent, INamedTypeSymbol type, string typeName)
        {
            var main = type.GetMembers("Main").OfType<IMethodSymbol>().FirstOrDefault(method => method.DeclaredAccessibility == Accessibility.Public && method.IsStatic == false && method.Parameters.Length == 0 && (method.ReturnsVoid || IsTask(method.ReturnType)));
            if (main == null)
            {
                source.Append(indent).Append("        null,").AppendLine();
                source.Append(indent).Append("        null");
                return;
            }

            if (main.ReturnsVoid)
            {
                source.Append(indent).Append("        static instance => instance.Main(),").AppendLine();
                source.Append(indent).Append("        null");
            }
            else
            {
                source.Append(indent).Append("        null,").AppendLine();
                source.Append(indent).Append("        static instance => instance.Main()");
            }
        }

        private static void AppendGeneratedActions(StringBuilder source, string indent, string typeName, List<ActionPlan> plans)
        {
            if (plans.Count == 0)
            {
                source.Append(indent).AppendLine("        null");
                return;
            }

            source.Append(indent).AppendLine("        new global::PowerArgs.GeneratedActionSpec[]");
            source.Append(indent).AppendLine("        {");
            foreach (var plan in plans)
            {
                source.Append(indent).Append("            new global::PowerArgs.GeneratedActionSpec(").Append(ToLiteral(plan.Method.Name)).Append(", ").Append(plan.IgnoreCase ? "true" : "false").Append(", ");
                if (plan.Method.Parameters.Length == 0)
                {
                    if (plan.Method.IsStatic) source.Append("static _ => ").Append(typeName).Append('.').Append(Escape(plan.Method.Name)).Append("()");
                    else source.Append("static instance => ((").Append(typeName).Append(")instance).").Append(Escape(plan.Method.Name)).Append("()");
                }
                else
                {
                    AppendGeneratedActionWithArguments(source, plan, typeName);
                }
                foreach (var alias in plan.Aliases) source.Append(", ").Append(ToLiteral(alias));
                source.AppendLine("),");
            }
            source.Append(indent).AppendLine("        }");
        }

        private static void AppendGeneratedActionWithArguments(StringBuilder source, ActionPlan plan, string typeName)
        {
            var actionArgumentType = plan.UsesArgumentModel ? plan.Method.Parameters[0].Type.ToDisplayString(TypeFormat) : "global::System.Object[]";
            if (plan.UsesArgumentModel) source.Append("static () => new ").Append(actionArgumentType).Append("(), ");
            else source.Append("static () => new global::System.Object[").Append(plan.ParameterArguments.Count).Append("], ");
            source.Append("static (arguments, index, value) => { ");
            if (plan.UsesArgumentModel)
            {
                for (var i = 0; i < plan.ArgumentProperties.Count; i++) source.Append("if (index == ").Append(i).Append(") { ((").Append(actionArgumentType).Append(")arguments).").Append(Escape(plan.ArgumentProperties[i].Property.Name)).Append(" = (").Append(plan.ArgumentProperties[i].Property.Type.ToDisplayString(TypeFormat)).Append(")value; return; } ");
            }
            else
            {
                for (var i = 0; i < plan.ParameterArguments.Count; i++) source.Append("if (index == ").Append(i).Append(") { ((global::System.Object[])arguments)[").Append(i).Append("] = value; return; } ");
            }
            source.Append("throw new global::System.ArgumentOutOfRangeException(nameof(index)); }, ");
            AppendActionArgumentSpecs(source, plan);
            source.Append(", ").Append(plan.UsesArgumentModel ? "true" : "false").Append(", ");
            if (plan.Method.IsStatic) source.Append("static (_, arguments) => ").Append(typeName).Append('.').Append(Escape(plan.Method.Name));
            else source.Append("static (instance, arguments) => ((").Append(typeName).Append(")instance).").Append(Escape(plan.Method.Name));
            source.Append('(');
            if (plan.UsesArgumentModel) source.Append('(').Append(actionArgumentType).Append(")arguments!");
            else
            {
                for (var i = 0; i < plan.ParameterArguments.Count; i++)
                {
                    if (i > 0) source.Append(", ");
                    source.Append('(').Append(plan.ParameterArguments[i].Parameter.Type.ToDisplayString(TypeFormat)).Append(")((global::System.Object[])arguments!)[").Append(i).Append(']');
                }
            }
            source.Append(')');
        }

        private static void AppendActionArgumentSpecs(StringBuilder source, ActionPlan plan)
        {
            source.Append("new global::PowerArgs.GeneratedArgumentSpec[] { ");
            foreach (var argument in plan.ArgumentProperties)
            {
                AppendGeneratedArgumentSpec(source, argument.Property.Name, argument.Property.Type, argument.IsRequired, argument.Position, argument.IgnoreCase, argument.RequiresValidation, argument.Aliases);
            }
            foreach (var argument in plan.ParameterArguments)
            {
                AppendGeneratedArgumentSpec(source, argument.Parameter.Name, argument.Parameter.Type, argument.IsRequired, argument.Position, argument.IgnoreCase, argument.RequiresValidation, argument.Aliases);
            }
            source.Append("}");
        }

        private static void AppendGeneratedArgumentSpec(StringBuilder source, string name, ITypeSymbol type, bool required, int position, bool ignoreCase, bool requiresValidation, List<string> aliases)
        {
            source.Append("new global::PowerArgs.GeneratedArgumentSpec(").Append(ToLiteral(name)).Append(", typeof(").Append(type.ToDisplayString(TypeFormat)).Append("), ").Append(required ? "true" : "false").Append(", ").Append(position).Append(", ").Append(ignoreCase ? "true" : "false").Append(", ").Append(requiresValidation ? "true" : "false");
            foreach (var alias in aliases) source.Append(", ").Append(ToLiteral(alias));
            source.Append("), ");
        }

        private static void AppendDirectArguments(StringBuilder source, string indent, List<ArgumentPlan> plans)
        {
            if (CanGenerateDirectParser(plans) == false)
            {
                source.Append(indent).AppendLine("        null");
                return;
            }

            source.Append(indent).AppendLine("        new global::PowerArgs.GeneratedArgumentSpec[]");
            source.Append(indent).AppendLine("        {");
            foreach (var plan in plans)
            {
                var property = plan.Property;
                source.Append(indent).Append("            new global::PowerArgs.GeneratedArgumentSpec(").Append(ToLiteral(property.Name)).Append(", typeof(").Append(property.Type.ToDisplayString(TypeFormat)).Append("), ").Append(plan.IsRequired ? "true" : "false").Append(", ").Append(plan.Position).Append(", ").Append(plan.IgnoreCase ? "true" : "false").Append(", ").Append(plan.RequiresValidation ? "true" : "false");
                foreach (var alias in plan.Aliases) source.Append(", ").Append(ToLiteral(alias));
                source.AppendLine("),");
            }
            source.Append(indent).AppendLine("        }");
        }

        private static bool CanGenerateDirectParser(List<ArgumentPlan> plans)
        {
            foreach (var plan in plans)
            {
                var property = plan.Property;
                if (IsDirectType(property.Type) == false) return false;
                if (property.GetAttributes().Where(IsArgRequired).Any(attribute => attribute.NamedArguments.Length > 0 || attribute.ConstructorArguments.Length > 0)) return false;
            }
            return true;
        }

        private static List<ArgumentPlan> BuildArgumentPlans(INamedTypeSymbol type, List<IPropertySymbol> properties)
        {
            var knownAliases = new List<string>();
            foreach (var property in properties)
            {
                foreach (var shortcutAttribute in property.GetAttributes().Where(IsArgShortcut))
                {
                    var shortcut = GetShortcutValue(shortcutAttribute);
                    if (shortcut != null) knownAliases.Add(shortcut);
                }
            }

            var plans = new List<ArgumentPlan>();
            var typeIgnoreCase = GetIgnoreCase(type.GetAttributes(), true);
            foreach (var property in properties)
            {
                var shortcutAttributes = property.GetAttributes().Where(IsArgShortcut).ToList();
                var includePropertyName = shortcutAttributes.Any(IsShortcutsOnly) == false;
                var aliases = new List<string>();
                if (includePropertyName)
                {
                    aliases.Add(property.Name);
                    knownAliases.Add(property.Name);
                }

                string? automaticShortcut = null;
                if (shortcutAttributes.Count == 0)
                {
                    automaticShortcut = FindShortcut(property.Name, knownAliases);
                    if (automaticShortcut != null)
                    {
                        aliases.Add(automaticShortcut);
                        knownAliases.Add(automaticShortcut);
                    }
                }

                foreach (var shortcutAttribute in shortcutAttributes)
                {
                    var shortcut = NormalizeShortcut(GetShortcutValue(shortcutAttribute));
                    if (shortcut != null) aliases.Add(shortcut);
                }

                var propertyIgnoreCase = GetIgnoreCase(property.GetAttributes(), typeIgnoreCase);
                var positionAttribute = property.GetAttributes().FirstOrDefault(IsArgPosition);
                var position = positionAttribute == null ? -1 : Convert.ToInt32(positionAttribute.ConstructorArguments[0].Value, System.Globalization.CultureInfo.InvariantCulture);
                plans.Add(new ArgumentPlan(property, aliases, includePropertyName, automaticShortcut, property.GetAttributes().Any(IsArgRequired), position, propertyIgnoreCase, property.GetAttributes().Any(IsArgRange)));
            }
            return plans;
        }

        private static List<ActionPlan> BuildActionPlans(INamedTypeSymbol type)
        {
            var plans = new List<ActionPlan>();
            var typeIgnoreCase = GetIgnoreCase(type.GetAttributes(), true);
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>().Where(method => method.GetAttributes().Any(IsArgActionMethod)))
            {
                var shortcutAttributes = method.GetAttributes().Where(IsArgShortcut).ToList();
                var includeMethodName = shortcutAttributes.Any(IsShortcutsOnly) == false;
                var aliases = new List<string>();
                if (includeMethodName) aliases.Add(method.Name);
                foreach (var shortcutAttribute in shortcutAttributes)
                {
                    var shortcut = GetShortcutValue(shortcutAttribute);
                    if (shortcut != null) aliases.Add(shortcut);
                }
                var argumentProperties = new List<ArgumentPlan>();
                var parameterArguments = new List<ActionParameterPlan>();
                var usesArgumentModel = method.Parameters.Length == 1 && IsDirectType(method.Parameters[0].Type) == false;
                if (usesArgumentModel)
                {
                    var argumentType = (INamedTypeSymbol)method.Parameters[0].Type;
                    argumentProperties = BuildArgumentPlans(argumentType, GetActionArgumentProperties(argumentType));
                }
                else
                {
                    for (var parameterIndex = 0; parameterIndex < method.Parameters.Length; parameterIndex++)
                    {
                        var parameter = method.Parameters[parameterIndex];
                        var parameterAliases = new List<string> { parameter.Name };
                        foreach (var shortcutAttribute in parameter.GetAttributes().Where(IsArgShortcut))
                        {
                            var shortcut = NormalizeShortcut(GetShortcutValue(shortcutAttribute));
                            if (shortcut != null) parameterAliases.Add(shortcut);
                        }
                        parameterArguments.Add(new ActionParameterPlan(parameter, parameterAliases, parameter.GetAttributes().Any(IsArgRequired), parameterIndex + 1, GetIgnoreCase(parameter.GetAttributes(), typeIgnoreCase), parameter.GetAttributes().Any(IsArgRange)));
                    }
                }
                plans.Add(new ActionPlan(method, aliases, includeMethodName, GetIgnoreCase(method.GetAttributes(), typeIgnoreCase), usesArgumentModel, argumentProperties, parameterArguments));
            }
            return plans;
        }

        private static bool GetIgnoreCase(IEnumerable<AttributeData> attributes, bool defaultValue)
        {
            foreach (var attribute in attributes)
            {
                if (attribute.AttributeClass?.Name == "ArgEnforceCase") return false;
                if (attribute.AttributeClass?.Name != "ArgIgnoreCase") continue;
                if (attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is bool value && value == false) return false;
            }
            return defaultValue;
        }

        private static bool IsArgShortcut(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgShortcut" && IsPowerArgsAttribute(attribute);
        private static bool IsArgPosition(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgPosition" && IsPowerArgsAttribute(attribute);
        private static bool IsArgRange(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgRange" && IsPowerArgsAttribute(attribute);

        private static bool IsShortcutsOnly(AttributeData attribute)
        {
            if (attribute.ConstructorArguments.Length == 0 || attribute.ConstructorArguments[0].Type?.TypeKind != TypeKind.Enum) return false;
            return Convert.ToInt32(attribute.ConstructorArguments[0].Value, System.Globalization.CultureInfo.InvariantCulture) == 2;
        }

        private static string? GetShortcutValue(AttributeData attribute)
        {
            if (attribute.ConstructorArguments.Length == 0 || attribute.ConstructorArguments[0].Value is string == false) return null;
            return (string)attribute.ConstructorArguments[0].Value!;
        }

        private static string? NormalizeShortcut(string? shortcut)
        {
            if (shortcut == null || shortcut.Length == 0) return shortcut;
            return shortcut[0] == '-' || shortcut[0] == '/' ? shortcut.Substring(1) : shortcut;
        }

