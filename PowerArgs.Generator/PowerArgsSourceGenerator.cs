using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PowerArgs.Generator
{
    [Generator]
    public sealed class PowerArgsSourceGenerator : IIncrementalGenerator
    {
        private static readonly SymbolDisplayFormat TypeFormat = new SymbolDisplayFormat(
            globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Included,
            typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
            genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
            miscellaneousOptions: SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

        private static readonly SymbolDisplayFormat RuntimeTypeFormat = TypeFormat.WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var partialProperties = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is PropertyDeclarationSyntax property && property.Modifiers.Any(SyntaxKind.PartialKeyword),
                static (syntaxContext, _) => syntaxContext.SemanticModel.GetDeclaredSymbol((PropertyDeclarationSyntax)syntaxContext.Node) as IPropertySymbol)
                .Where(static property => property != null && property.PartialDefinitionPart == null && property.PartialImplementationPart == null);

            var partialClasses = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax declaration && declaration.Modifiers.Any(SyntaxKind.PartialKeyword),
                static (syntaxContext, _) => syntaxContext.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)syntaxContext.Node) as INamedTypeSymbol)
                .Where(static type => type != null);

            context.RegisterSourceOutput(partialProperties.Collect().Combine(partialClasses.Collect()), static (productionContext, candidates) => Generate(productionContext, candidates.Left, candidates.Right));
        }

        private static void Generate(SourceProductionContext context, ImmutableArray<IPropertySymbol?> discoveredProperties, ImmutableArray<INamedTypeSymbol?> discoveredClasses)
        {
            var models = new Dictionary<INamedTypeSymbol, List<IPropertySymbol>>(SymbolEqualityComparer.Default);
            foreach (var property in discoveredProperties)
            {
                if (property == null || property.ContainingType.TypeKind != TypeKind.Class || property.ContainingType.TypeParameters.Length != 0) continue;
                if (CanReopen(property.ContainingType) == false) continue;

                if (models.TryGetValue(property.ContainingType, out var properties) == false)
                {
                    properties = new List<IPropertySymbol>();
                    models.Add(property.ContainingType, properties);
                }
                if (properties.Any(existing => SymbolEqualityComparer.Default.Equals(existing, property)) == false) properties.Add(property);
            }

            foreach (var type in discoveredClasses)
            {
                if (type == null || CanReopen(type) == false || models.ContainsKey(type)) continue;
                // A partial class with a command entry point opts in even without a partial property.
                if (GetPublicMethods(type).Any(method => IsMain(method) || GetInheritedAttributes(method).Any(IsArgActionMethod))) models.Add(type, new List<IPropertySymbol>());
            }

            foreach (var pair in models)
            {
                pair.Value.Sort((left, right) => left.Locations.First().SourceSpan.Start.CompareTo(right.Locations.First().SourceSpan.Start));
                context.AddSource(MakeHintName(pair.Key), SourceText.From(GenerateModel(pair.Key, pair.Value), Encoding.UTF8));
            }
        }

        private static bool CanReopen(INamedTypeSymbol type)
        {
            for (var current = type; current != null; current = current.ContainingType)
            {
                if (current.TypeParameters.Length != 0) return false;
                if (current.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax() is TypeDeclarationSyntax declaration && declaration.Modifiers.Any(SyntaxKind.PartialKeyword)) == false) return false;
            }
            return true;
        }

        private static string GenerateModel(INamedTypeSymbol type, List<IPropertySymbol> partialProperties)
        {
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("#nullable enable");

            if (type.ContainingNamespace.IsGlobalNamespace == false)
            {
                source.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
                source.AppendLine();
            }

            var containingTypes = GetContainingTypes(type);
            for (var i = 0; i < containingTypes.Count; i++)
            {
                source.Append(' ', i * 4).Append(GetAccessibility(containingTypes[i].DeclaredAccessibility)).Append(" partial class ").Append(Escape(containingTypes[i].Name)).AppendLine();
                source.Append(' ', i * 4).AppendLine("{");
            }

            var bodyIndent = new string(' ', containingTypes.Count * 4);
            for (var i = 0; i < partialProperties.Count; i++)
            {
                AppendPropertyImplementation(source, bodyIndent, partialProperties[i], i);
            }

            if (CanGenerateModel(type, partialProperties, out var argumentProperties, out var useDirectParser))
            {
                AppendGeneratedModel(source, bodyIndent, type, argumentProperties, useDirectParser);
            }

            for (var i = containingTypes.Count - 1; i >= 0; i--)
            {
                source.Append(' ', i * 4).AppendLine("}");
            }

            return source.ToString();
        }

        private static List<INamedTypeSymbol> GetContainingTypes(INamedTypeSymbol type)
        {
            var result = new List<INamedTypeSymbol>();
            for (var current = type; current != null; current = current.ContainingType) result.Add(current);
            result.Reverse();
            return result;
        }

        private static void AppendPropertyImplementation(StringBuilder source, string indent, IPropertySymbol property, int propertyIndex)
        {
            var fieldName = "__powerArgsGeneratedValue" + propertyIndex;
            var propertyType = property.Type.ToDisplayString(TypeFormat);
            var staticText = property.IsStatic ? "static " : string.Empty;
            source.Append(indent).Append("private ").Append(staticText).Append(propertyType).Append(' ').Append(fieldName).AppendLine(" = default!;");
            source.Append(indent).Append(GetAccessibility(property.DeclaredAccessibility)).Append(' ').Append(staticText).Append("partial ").Append(propertyType).Append(' ').Append(Escape(property.Name)).AppendLine();
            source.Append(indent).AppendLine("{");
            if (property.GetMethod != null)
            {
                source.Append(indent).Append("    ").Append(GetAccessorAccessibility(property, property.GetMethod)).Append("get => ").Append(fieldName).AppendLine(";");
            }
            if (property.SetMethod != null)
            {
                source.Append(indent).Append("    ").Append(GetAccessorAccessibility(property, property.SetMethod)).Append(property.SetMethod.IsInitOnly ? "init" : "set").Append(" => ").Append(fieldName).AppendLine(" = value;");
            }
            source.Append(indent).AppendLine("}");
            source.AppendLine();
        }

        private static string GetAccessorAccessibility(IPropertySymbol property, IMethodSymbol accessor)
        {
            return accessor.DeclaredAccessibility == property.DeclaredAccessibility ? string.Empty : GetAccessibility(accessor.DeclaredAccessibility) + " ";
        }

        private static bool CanGenerateModel(INamedTypeSymbol type, List<IPropertySymbol> partialProperties, out List<IPropertySymbol> argumentProperties, out bool useDirectParser)
        {
            var publicProperties = GetPublicProperties(type);

            argumentProperties = new List<IPropertySymbol>();
            useDirectParser = true;
            if (type.IsAbstract || type.IsStatic) return false;
            // Module initializers must be callable from the containing assembly.
            if (GetContainingTypes(type).Any(containing => containing.DeclaredAccessibility != Accessibility.Public && containing.DeclaredAccessibility != Accessibility.Internal && containing.DeclaredAccessibility != Accessibility.ProtectedOrInternal)) return false;
            if (type.InstanceConstructors.Any(constructor => constructor.Parameters.Length == 0) == false) return false;
            // External action discovery and the legacy Action property require reflected mapping.
            if (GetInheritedAttributes(type).Any(attribute => IsDerivedFrom(attribute.AttributeClass, "PowerArgs.ArgActionType") || IsDerivedFrom(attribute.AttributeClass, "PowerArgs.ArgActionResolver"))) return false;
            if (publicProperties.Any(property => property.Name == "Action" && property.GetAttributes().Any(IsArgRequired) && property.GetAttributes().Any(attribute => IsArgPosition(attribute) && attribute.ConstructorArguments[0].Value is int position && position == 0))) return false;
            if (GetInheritedAttributes(type).Any(attribute => IsDefinitionMetadata(attribute) && CanGenerateAttribute(attribute) == false)) return false;
            if (GetInheritedAttributes(type).Any(attribute => IsDefinitionMetadata(attribute) && IsSupportedDirectTypeAttribute(attribute) == false)) useDirectParser = false;
            if (GetInheritedAttributes(type).Count(IsCaseAttribute) > 1) return false;
            foreach (var method in GetPublicMethods(type))
            {
                // Ordinary helpers are not part of the command-line contract.
                if (GetInheritedAttributes(method).Any(IsArgActionMethod) == false) continue;
                if (method.ReturnsVoid == false && IsTask(method.ReturnType) == false) return false;
                if (GetInheritedAttributes(method).Any(attribute => IsActionMetadata(attribute) && (IsSupportedActionAttribute(attribute) == false || CanGenerateAttribute(attribute) == false))) return false;
                if (GetInheritedAttributes(method).Count(IsCaseAttribute) > 1) return false;
                if (CanGenerateAction(method, type, out var directAction) == false) return false;
                if (directAction == false) useDirectParser = false;
            }

            foreach (var property in publicProperties)
            {
                if (SymbolEqualityComparer.Default.Equals(property.ContainingType, type) && partialProperties.Any(candidate => SymbolEqualityComparer.Default.Equals(candidate, property)) == false) return false;
                if (property.GetMethod == null || property.SetMethod == null || property.SetMethod.IsInitOnly || property.GetMethod.DeclaredAccessibility != Accessibility.Public || property.SetMethod.DeclaredAccessibility != Accessibility.Public) return false;
                if (property.GetAttributes().Any(attribute => IsArgumentMetadata(attribute) && CanGenerateAttribute(attribute) == false)) return false;
                if (property.GetAttributes().Count(IsCaseAttribute) > 1) return false;
                if (property.GetAttributes().Any(IsArgIgnore) == false)
                {
                    argumentProperties.Add(property);
                    if (CanUseDirectArgument(property.Type, property.GetAttributes()) == false) useDirectParser = false;
                }
            }

            return argumentProperties.Count > 0 || GetPublicMethods(type).Any(method => IsMain(method) || GetInheritedAttributes(method).Any(IsArgActionMethod));
        }

        private static bool IsMain(IMethodSymbol method) => method.Name == "Main" && !method.IsStatic && method.Parameters.Length == 0 && method.TypeParameters.Length == 0 && (method.ReturnsVoid || IsTask(method.ReturnType));

        private static List<IMethodSymbol> GetPublicMethods(INamedTypeSymbol type)
        {
            var methods = new List<IMethodSymbol>();
            for (var current = type; current != null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
            {
                foreach (var method in current.GetMembers().OfType<IMethodSymbol>().Where(method => method.MethodKind == MethodKind.Ordinary && method.DeclaredAccessibility == Accessibility.Public))
                {
                    // Reflection's public instance/static lookup does not flatten inherited static methods.
                    if (method.IsStatic && !SymbolEqualityComparer.Default.Equals(current, type)) continue;
                    // New/hidden methods retain the base method in reflection's method list;
                    // only an override replaces the inherited virtual slot.
                    if (methods.Any(existing => Overrides(existing, method))) continue;
                    methods.Add(method);
                }
            }
            return methods;
        }

        private static bool Overrides(IMethodSymbol candidate, IMethodSymbol method)
        {
            for (var overridden = candidate.OverriddenMethod; overridden != null; overridden = overridden.OverriddenMethod)
                if (SymbolEqualityComparer.Default.Equals(overridden, method)) return true;
            return false;
        }

        private static ImmutableArray<AttributeData> GetInheritedAttributes(ISymbol symbol)
        {
            var attributes = symbol.GetAttributes().ToList();
            ISymbol? ancestor = symbol is IMethodSymbol method ? method.OverriddenMethod : (symbol as INamedTypeSymbol)?.BaseType;
            while (ancestor != null)
            {
                foreach (var attribute in ancestor.GetAttributes())
                {
                    AttributeData? usage = null;
                    for (var attributeType = attribute.AttributeClass; attributeType != null && usage == null; attributeType = attributeType.BaseType)
                        usage = attributeType.GetAttributes().FirstOrDefault(candidate => candidate.AttributeClass?.ToDisplayString() == "System.AttributeUsageAttribute");
                    if (usage != null && usage.NamedArguments.Any(pair => pair.Key == "Inherited" && pair.Value.Value is false)) continue;
                    var allowMultiple = usage != null && usage.NamedArguments.Any(pair => pair.Key == "AllowMultiple" && pair.Value.Value is true);
                    if (!allowMultiple && attributes.Any(existing => SymbolEqualityComparer.Default.Equals(existing.AttributeClass, attribute.AttributeClass))) continue;
                    attributes.Add(attribute);
                }
                ancestor = ancestor is IMethodSymbol baseMethod ? baseMethod.OverriddenMethod : (ancestor as INamedTypeSymbol)?.BaseType;
            }
            return attributes.ToImmutableArray();
        }

        private static List<IPropertySymbol> GetPublicProperties(INamedTypeSymbol type)
        {
            var hierarchy = new List<INamedTypeSymbol>();
            for (var current = type; current != null && current.SpecialType != SpecialType.System_Object; current = current.BaseType) hierarchy.Add(current);
            var properties = new List<IPropertySymbol>();
            foreach (var current in hierarchy)
            {
                // Match Type.GetProperties: declared members first, then inherited members;
                // an override (or same-signature hidden property) replaces its base member.
                foreach (var property in current.GetMembers().OfType<IPropertySymbol>()
                    .Where(property => property.IsStatic == false && property.DeclaredAccessibility == Accessibility.Public && property.IsIndexer == false)
                    .OrderBy(property => property.Locations.FirstOrDefault()?.SourceSpan.Start ?? int.MaxValue))
                {
                    if (properties.Any(existing => existing.Name == property.Name && SymbolEqualityComparer.Default.Equals(existing.Type, property.Type))) continue;
                    properties.Add(property);
                }
            }
            return properties;
        }

        private static bool IsPowerArgsAttribute(AttributeData attribute) => attribute.AttributeClass?.ContainingNamespace.ToDisplayString() == "PowerArgs";

        private static bool IsDefinitionMetadata(AttributeData attribute) => ImplementsInterface(attribute.AttributeClass, "PowerArgs.ICommandLineArgumentsDefinitionMetadata");

        private static bool IsArgumentMetadata(AttributeData attribute) => ImplementsInterface(attribute.AttributeClass, "PowerArgs.ICommandLineArgumentMetadata");

        private static bool IsActionMetadata(AttributeData attribute) => ImplementsInterface(attribute.AttributeClass, "PowerArgs.ICommandLineActionMetadata");

        private static bool ImplementsInterface(INamedTypeSymbol? type, string interfaceName) => type != null && type.AllInterfaces.Any(candidate => candidate.ToDisplayString() == interfaceName);

        private static bool IsArgRequired(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgRequired" && IsPowerArgsAttribute(attribute);

        private static bool IsArgIgnore(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgIgnoreAttribute" && IsPowerArgsAttribute(attribute);

        private static bool IsArgActionMethod(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgActionMethod" && IsPowerArgsAttribute(attribute);

        private static bool IsCaseAttribute(AttributeData attribute) => (attribute.AttributeClass?.Name == "ArgIgnoreCase" || attribute.AttributeClass?.Name == "ArgEnforceCase") && IsPowerArgsAttribute(attribute);

        private static bool IsSupportedDirectTypeAttribute(AttributeData attribute)
        {
            var name = attribute.AttributeClass?.Name;
            return name == "ArgDescription" || name == "ArgIgnoreCase" || name == "ArgEnforceCase" || name == "ArgExample" || name == "ArgProductName" || name == "ArgProductVersion" || name == "ArgCopyright" || name == "ArgExceptionBehavior";
        }

        private static bool IsSupportedDirectPropertyAttribute(AttributeData attribute)
        {
            var name = attribute.AttributeClass?.Name;
            return IsDerivedFrom(attribute.AttributeClass, "PowerArgs.ArgValidator") || IsBuiltinExclusion(attribute) || name == "HelpHook" || name == "ArgShortcut" || name == "ArgDescription" || name == "ArgPosition" || name == "ArgIgnoreAttribute" || name == "ArgIgnoreCase" || name == "ArgEnforceCase" || name == "DefaultValueAttribute" || name == "ArgDefaultValueAttribute" || name == "OmitFromUsageDocs" || name == "ArgExample";
        }

        private static bool IsDerivedFrom(INamedTypeSymbol? type, string baseTypeName)
        {
            for (var current = type; current != null; current = current.BaseType) if (current.ToDisplayString() == baseTypeName) return true;
            return false;
        }

        private static bool IsSupportedActionAttribute(AttributeData attribute)
        {
            var name = attribute.AttributeClass?.Name;
            return name == "ArgActionMethod" || name == "ArgShortcut" || name == "ArgDescription" || name == "ArgIgnoreCase" || name == "ArgEnforceCase" || name == "OmitFromUsageDocs" || name == "ArgExample";
        }

        private static bool IsTask(ITypeSymbol type) => type.ToDisplayString() == "System.Threading.Tasks.Task";

        private static bool CanGenerateAction(IMethodSymbol method, INamedTypeSymbol parentType, out bool useDirectParser)
        {
            useDirectParser = true;
            if (method.TypeParameters.Length != 0 || method.Parameters.Any(parameter => parameter.RefKind != RefKind.None || parameter.HasExplicitDefaultValue)) return false;
            if (method.Parameters.Length == 0) return true;
            if (method.Parameters.All(parameter => IsDirectType(parameter.Type)))
            {
                useDirectParser = method.Parameters.All(parameter => CanUseDirectArgument(parameter.Type, parameter.GetAttributes()));
                return method.Parameters.All(parameter => parameter.GetAttributes().All(attribute => !IsArgumentMetadata(attribute) || CanGenerateAttribute(attribute)) && parameter.GetAttributes().Count(IsCaseAttribute) <= 1);
            }
            if (method.Parameters.Length != 1 || method.Parameters[0].Type is INamedTypeSymbol == false) return false;

            var argumentType = (INamedTypeSymbol)method.Parameters[0].Type;
            if (argumentType.TypeKind != TypeKind.Class || argumentType.IsAbstract || argumentType.InstanceConstructors.Any(constructor => constructor.Parameters.Length == 0 && constructor.DeclaredAccessibility != Accessibility.Private) == false) return false;
            if (GetInheritedAttributes(argumentType).Any(attribute => IsDefinitionMetadata(attribute) && IsSupportedDirectTypeAttribute(attribute) == false)) return false;
            if (GetIgnoreCase(GetInheritedAttributes(argumentType), true) != GetIgnoreCase(GetInheritedAttributes(parentType), true)) return false;
            foreach (var property in GetActionArgumentProperties(argumentType))
            {
                if (property.GetMethod == null || property.SetMethod == null || property.SetMethod.IsInitOnly || property.GetMethod.DeclaredAccessibility != Accessibility.Public || property.SetMethod.DeclaredAccessibility != Accessibility.Public) return false;
                if (IsDirectType(property.Type) == false || property.GetAttributes().Any(attribute => IsArgumentMetadata(attribute) && !CanGenerateAttribute(attribute))) return false;
                if (CanUseDirectArgument(property.Type, property.GetAttributes()) == false) useDirectParser = false;
                if (property.GetAttributes().Count(IsCaseAttribute) > 1) return false;
            }
            return true;
        }

        private static bool HasDirectRequiredMetadata(IEnumerable<AttributeData> attributes) => attributes.Where(IsArgRequired).All(attribute => attribute.NamedArguments.All(pair => pair.Key == "If" || pair.Key == "IfNot" || pair.Key == "Priority" || (pair.Key == "PromptIfMissing" && pair.Value.Value is false)));

        private static bool IsConditionalRequired(AttributeData attribute) => IsArgRequired(attribute) && attribute.NamedArguments.Any(pair => (pair.Key == "If" || pair.Key == "IfNot") && pair.Value.Value != null);
        private static bool IsUnconditionalRequired(AttributeData attribute) => IsArgRequired(attribute) && !IsConditionalRequired(attribute);
        private static bool IsBuiltinExclusion(AttributeData attribute) => attribute.AttributeClass?.ToDisplayString() == "PowerArgs.ArgCantBeCombinedWith";
        private static bool RequiresPostValidation(AttributeData attribute) => IsConditionalRequired(attribute) || IsBuiltinExclusion(attribute);
        private static bool IsBuiltinValidator(AttributeData attribute)
        {
            var name = attribute.AttributeClass?.ToDisplayString();
            return name == "PowerArgs.ArgRequired" || name == "PowerArgs.ArgRange" || name == "PowerArgs.ArgRegex" || name == "PowerArgs.ArgExistingFile" || name == "PowerArgs.ArgExistingDirectory";
        }

        private static List<IPropertySymbol> GetActionArgumentProperties(INamedTypeSymbol type) => GetPublicProperties(type)
            .Where(property => property.GetAttributes().Any(IsArgIgnore) == false)
            .ToList();

        private static void AppendGeneratedModel(StringBuilder source, string indent, INamedTypeSymbol type, List<IPropertySymbol> properties, bool useDirectParser)
        {
            var typeName = type.ToDisplayString(TypeFormat);
            var plans = BuildArgumentPlans(type, properties);
            var actionPlans = BuildActionPlans(type);
            source.Append(indent).AppendLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            source.Append(indent).AppendLine("internal static void __RegisterPowerArgsGeneratedModel()");
            source.Append(indent).AppendLine("{");
            source.Append(indent).Append("    global::PowerArgs.GeneratedArgumentModelRegistry.Register<").Append(typeName).AppendLine(">(");
            source.Append(indent).Append("        static () => new ").Append(typeName).AppendLine("(),");
            source.Append(indent).AppendLine("        static definition =>");
            source.Append(indent).AppendLine("        {");

            foreach (var attribute in GetInheritedAttributes(type).Where(IsDefinitionMetadata))
            {
                source.Append(indent).Append("            definition.Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
            }

            for (var i = 0; i < plans.Count; i++)
            {
                var plan = plans[i];
                var property = plan.Property;
                var variableName = "argument" + i;
                source.Append(indent).Append("            var ").Append(variableName).Append(" = global::PowerArgs.CommandLineArgument.CreateGenerated(typeof(").Append(property.Type.ToDisplayString(RuntimeTypeFormat)).Append("), ").Append(plan.IncludePropertyName ? ToLiteral(property.Name) : "null").Append(", ").Append(plan.IgnoreCase ? "true" : "false").AppendLine(");");
                if (plan.AutomaticShortcut != null)
                {
                    source.Append(indent).Append("            ").Append(variableName).Append(".Aliases.Add(").Append(ToLiteral(plan.AutomaticShortcut)).AppendLine(");");
                }

                foreach (var attribute in property.GetAttributes().Where(attribute => IsArgumentMetadata(attribute) && IsArgIgnore(attribute) == false))
                {
                    source.Append(indent).Append("            ").Append(variableName).Append(".Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
                }
                if (plan.Position >= 0) source.Append(indent).Append("            ").Append(variableName).Append(".Position = ").Append(plan.Position).AppendLine(";");
                source.Append(indent).Append("            definition.Arguments.Add(").Append(variableName).AppendLine(");");
            }

            for (var i = 0; i < actionPlans.Count; i++)
            {
                var plan = actionPlans[i];
                var variableName = "action" + i;
                source.Append(indent).Append("            var ").Append(variableName).Append(" = global::PowerArgs.CommandLineAction.CreateGenerated(").Append(plan.IncludeMethodName ? ToLiteral(plan.Method.Name) : "null").Append(", ").Append(plan.IgnoreCase ? "true" : "false").AppendLine(");");
                foreach (var attribute in GetInheritedAttributes(plan.Method).Where(IsActionMetadata)) source.Append(indent).Append("            ").Append(variableName).Append(".Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
                for (var argumentIndex = 0; argumentIndex < plan.ArgumentProperties.Count; argumentIndex++)
                {
                    var argumentPlan = plan.ArgumentProperties[argumentIndex];
                    AppendGeneratedActionArgumentDefinition(source, indent, variableName, "actionArgument" + i + "_" + argumentIndex, argumentPlan.Property.Type, argumentPlan.Property.Name, argumentPlan.IgnoreCase, argumentPlan.Position, argumentPlan.AutomaticShortcut, argumentPlan.Property.GetAttributes());
                }
                for (var argumentIndex = 0; argumentIndex < plan.ParameterArguments.Count; argumentIndex++)
                {
                    var argumentPlan = plan.ParameterArguments[argumentIndex];
                    AppendGeneratedActionArgumentDefinition(source, indent, variableName, "actionArgument" + i + "_" + argumentIndex, argumentPlan.Parameter.Type, argumentPlan.Parameter.Name, argumentPlan.IgnoreCase, argumentPlan.Position, null, argumentPlan.Parameter.GetAttributes());
                }
                source.Append(indent).Append("            definition.Actions.Add(").Append(variableName).AppendLine(");");
            }

            source.Append(indent).AppendLine("        },");
            source.Append(indent).AppendLine("        static (instance, index, value) =>");
            source.Append(indent).AppendLine("        {");
            for (var i = 0; i < plans.Count; i++)
            {
                source.Append(indent).Append("            if (index == ").Append(i).Append(") { instance.").Append(Escape(plans[i].Property.Name)).Append(" = (").Append(plans[i].Property.Type.ToDisplayString(TypeFormat)).AppendLine(")value; return; }");
            }
            source.Append(indent).AppendLine("            throw new global::System.ArgumentOutOfRangeException(nameof(index));");
            source.Append(indent).Append("        },").AppendLine();
            if (useDirectParser) AppendDirectArguments(source, indent, plans);
            else source.Append(indent).Append("        null");
            source.AppendLine(",");
            AppendMainInvokers(source, indent, type, typeName);
            source.AppendLine(",");
            AppendGeneratedActions(source, indent, typeName, actionPlans);
            source.Append(indent).AppendLine("    );");
            source.Append(indent).AppendLine("}");
            source.AppendLine();
        }

        private static void AppendGeneratedActionArgumentDefinition(StringBuilder source, string indent, string actionVariable, string argumentVariable, ITypeSymbol argumentType, string argumentName, bool ignoreCase, int position, string? automaticShortcut, IEnumerable<AttributeData> attributes)
        {
            source.Append(indent).Append("            var ").Append(argumentVariable).Append(" = global::PowerArgs.CommandLineArgument.CreateGenerated(typeof(").Append(argumentType.ToDisplayString(RuntimeTypeFormat)).Append("), ").Append(ToLiteral(argumentName)).Append(", ").Append(ignoreCase ? "true" : "false").AppendLine(");");
            if (automaticShortcut != null) source.Append(indent).Append("            ").Append(argumentVariable).Append(".Aliases.Add(").Append(ToLiteral(automaticShortcut)).AppendLine(");");
            foreach (var attribute in attributes.Where(attribute => IsArgumentMetadata(attribute) && IsArgIgnore(attribute) == false)) source.Append(indent).Append("            ").Append(argumentVariable).Append(".Metadata.Add(").Append(GenerateAttribute(attribute)).AppendLine(");");
            if (position >= 0) source.Append(indent).Append("            ").Append(argumentVariable).Append(".Position = ").Append(position).AppendLine(";");
            source.Append(indent).Append("            ").Append(actionVariable).Append(".Arguments.Add(").Append(argumentVariable).AppendLine(");");
        }

        private static void AppendMainInvokers(StringBuilder source, string indent, INamedTypeSymbol type, string typeName)
        {
            var mainMethods = GetPublicMethods(type).Where(method => method.Name == "Main" && !method.IsStatic).ToList();
            var main = mainMethods.Count == 1 && IsMain(mainMethods[0]) ? mainMethods[0] : null;
            if (main == null)
            {
                source.Append(indent).Append("        null,").AppendLine();
                source.Append(indent).Append("        null");
                return;
            }

            if (main.ReturnsVoid)
            {
                source.Append(indent).Append("        static instance => ((").Append(main.ContainingType.ToDisplayString(TypeFormat)).Append(")instance).Main(),").AppendLine();
                source.Append(indent).Append("        null");
            }
            else
            {
                source.Append(indent).Append("        null,").AppendLine();
                source.Append(indent).Append("        static instance => ((").Append(main.ContainingType.ToDisplayString(TypeFormat)).Append(")instance).Main()");
            }
        }

        private static void AppendGeneratedActions(StringBuilder source, string indent, string typeName, List<ActionPlan> plans)
        {
            if (plans.Count == 0)
            {
                source.Append(indent).AppendLine("        null");
                return;
            }

            source.Append(indent).AppendLine("        new global::PowerArgs.GeneratedActionSpec[]");
            source.Append(indent).AppendLine("        {");
            foreach (var plan in plans)
            {
                source.Append(indent).Append("            new global::PowerArgs.GeneratedActionSpec(").Append(ToLiteral(plan.Method.Name)).Append(", ").Append(plan.IgnoreCase ? "true" : "false").Append(", ");
                if (plan.Method.Parameters.Length == 0)
                {
                    if (plan.Method.IsStatic) source.Append("static _ => ").Append(typeName).Append('.').Append(Escape(plan.Method.Name)).Append("()");
                    else source.Append("static instance => ((").Append(plan.Method.ContainingType.ToDisplayString(TypeFormat)).Append(")instance).").Append(Escape(plan.Method.Name)).Append("()");
                }
                else
                {
                    AppendGeneratedActionWithArguments(source, plan, typeName);
                }
                foreach (var alias in plan.Aliases) source.Append(", ").Append(ToLiteral(alias));
                source.AppendLine("),");
            }
            source.Append(indent).AppendLine("        }");
        }

        private static void AppendGeneratedActionWithArguments(StringBuilder source, ActionPlan plan, string typeName)
        {
            var actionArgumentType = plan.UsesArgumentModel ? plan.Method.Parameters[0].Type.ToDisplayString(RuntimeTypeFormat) : "global::System.Object[]";
            if (plan.UsesArgumentModel) source.Append("static () => new ").Append(actionArgumentType).Append("(), ");
            else
            {
                source.Append("static () => new global::System.Object[] { ");
                foreach (var argument in plan.ParameterArguments) source.Append("default(").Append(argument.Parameter.Type.ToDisplayString(TypeFormat)).Append(")!, ");
                source.Append("}, ");
            }
            source.Append("static (arguments, index, value) => { ");
            if (plan.UsesArgumentModel)
            {
                for (var i = 0; i < plan.ArgumentProperties.Count; i++) source.Append("if (index == ").Append(i).Append(") { ((").Append(actionArgumentType).Append(")arguments).").Append(Escape(plan.ArgumentProperties[i].Property.Name)).Append(" = value == null ? default! : (").Append(plan.ArgumentProperties[i].Property.Type.ToDisplayString(TypeFormat)).Append(")value; return; } ");
            }
            else
            {
                for (var i = 0; i < plan.ParameterArguments.Count; i++) source.Append("if (index == ").Append(i).Append(") { ((global::System.Object[])arguments)[").Append(i).Append("] = value; return; } ");
            }
            source.Append("throw new global::System.ArgumentOutOfRangeException(nameof(index)); }, ");
            AppendActionArgumentSpecs(source, plan);
            source.Append(", ").Append(plan.UsesArgumentModel ? "true" : "false").Append(", ");
            if (plan.Method.IsStatic) source.Append("static (_, arguments) => ").Append(typeName).Append('.').Append(Escape(plan.Method.Name));
            else source.Append("static (instance, arguments) => ((").Append(plan.Method.ContainingType.ToDisplayString(TypeFormat)).Append(")instance).").Append(Escape(plan.Method.Name));
            source.Append('(');
            if (plan.UsesArgumentModel) source.Append('(').Append(actionArgumentType).Append(")arguments!");
            else
            {
                for (var i = 0; i < plan.ParameterArguments.Count; i++)
                {
                    if (i > 0) source.Append(", ");
                    var parameterType = plan.ParameterArguments[i].Parameter.Type.ToDisplayString(TypeFormat);
                    source.Append("((global::System.Object[])arguments!)[").Append(i).Append("] == null ? default(").Append(parameterType).Append(")! : (").Append(parameterType).Append(")((global::System.Object[])arguments!)[").Append(i).Append(']');
                }
            }
            source.Append(')');
        }

        private static void AppendActionArgumentSpecs(StringBuilder source, ActionPlan plan)
        {
            source.Append("new global::PowerArgs.GeneratedArgumentSpec[] { ");
            foreach (var argument in plan.ArgumentProperties)
            {
                AppendGeneratedArgumentSpec(source, argument.Property.Name, argument.Property.Type, argument.IsRequired, argument.Position, argument.IgnoreCase, argument.RequiresValidation, argument.RequiresHookProcessing, argument.Aliases, argument.Property.GetAttributes());
            }
            foreach (var argument in plan.ParameterArguments)
            {
                AppendGeneratedArgumentSpec(source, argument.Parameter.Name, argument.Parameter.Type, argument.IsRequired, argument.Position, argument.IgnoreCase, argument.RequiresValidation, argument.RequiresHookProcessing, argument.Aliases, argument.Parameter.GetAttributes());
            }
            source.Append("}");
        }

        private static void AppendGeneratedArgumentSpec(StringBuilder source, string name, ITypeSymbol type, bool required, int position, bool ignoreCase, bool requiresValidation, bool requiresHookProcessing, List<string> aliases, ImmutableArray<AttributeData> attributes)
        {
            source.Append("new global::PowerArgs.GeneratedArgumentSpec(").Append(ToLiteral(name)).Append(", typeof(").Append(type.ToDisplayString(RuntimeTypeFormat)).Append("), ").Append(required ? "true" : "false").Append(", ").Append(position).Append(", ").Append(ignoreCase ? "true" : "false").Append(", ").Append(requiresValidation ? "true" : "false").Append(", ").Append(requiresHookProcessing ? "true" : "false");
            foreach (var alias in aliases) source.Append(", ").Append(ToLiteral(alias));
            source.Append(")");
            AppendArgumentFeatures(source, type, attributes);
            source.Append(", ");
        }

        private static void AppendDirectArguments(StringBuilder source, string indent, List<ArgumentPlan> plans)
        {
            if (CanGenerateDirectParser(plans) == false)
            {
                source.Append(indent).AppendLine("        null");
                return;
            }

            source.Append(indent).AppendLine("        new global::PowerArgs.GeneratedArgumentSpec[]");
            source.Append(indent).AppendLine("        {");
            foreach (var plan in plans)
            {
                var property = plan.Property;
                source.Append(indent).Append("            new global::PowerArgs.GeneratedArgumentSpec(").Append(ToLiteral(property.Name)).Append(", typeof(").Append(property.Type.ToDisplayString(RuntimeTypeFormat)).Append("), ").Append(plan.IsRequired ? "true" : "false").Append(", ").Append(plan.Position).Append(", ").Append(plan.IgnoreCase ? "true" : "false").Append(", ").Append(plan.RequiresValidation ? "true" : "false").Append(", ").Append(plan.RequiresHookProcessing ? "true" : "false");
                foreach (var alias in plan.Aliases) source.Append(", ").Append(ToLiteral(alias));
                source.Append(")");
                AppendArgumentFeatures(source, property.Type, property.GetAttributes());
                source.AppendLine(",");
            }
            source.Append(indent).AppendLine("        }");
        }

        private static bool CanGenerateDirectParser(List<ArgumentPlan> plans)
        {
            foreach (var plan in plans)
            {
                var property = plan.Property;
                if (!CanUseDirectArgument(property.Type, property.GetAttributes())) return false;
            }
            return true;
        }

        private static List<ArgumentPlan> BuildArgumentPlans(INamedTypeSymbol type, List<IPropertySymbol> properties)
        {
            var knownAliases = new List<string>();
            foreach (var property in properties)
            {
                foreach (var shortcutAttribute in property.GetAttributes().Where(IsArgShortcut))
                {
                    var shortcut = GetShortcutValue(shortcutAttribute);
                    if (shortcut != null) knownAliases.Add(shortcut);
                }
            }

            var plans = new List<ArgumentPlan>();
            foreach (var property in properties)
            {
                var shortcutAttributes = property.GetAttributes().Where(IsArgShortcut).ToList();
                var includePropertyName = shortcutAttributes.Any(IsShortcutsOnly) == false;
                var aliases = new List<string>();
                if (includePropertyName)
                {
                    aliases.Add(property.Name);
                    knownAliases.Add(property.Name);
                }

                string? automaticShortcut = null;
                if (shortcutAttributes.Count == 0)
                {
                    automaticShortcut = FindShortcut(property.Name, knownAliases);
                    if (automaticShortcut != null)
                    {
                        aliases.Add(automaticShortcut);
                        knownAliases.Add(automaticShortcut);
                    }
                }

                foreach (var shortcutAttribute in shortcutAttributes)
                {
                    var shortcut = NormalizeShortcut(GetShortcutValue(shortcutAttribute));
                    if (shortcut != null) aliases.Add(shortcut);
                }

                var propertyIgnoreCase = GetIgnoreCase(property.GetAttributes(), GetIgnoreCase(GetInheritedAttributes(property.ContainingType), true));
                var positionAttribute = property.GetAttributes().FirstOrDefault(IsArgPosition);
                var position = positionAttribute == null ? -1 : Convert.ToInt32(positionAttribute.ConstructorArguments[0].Value, System.Globalization.CultureInfo.InvariantCulture);
                plans.Add(new ArgumentPlan(property, aliases, includePropertyName, automaticShortcut, property.GetAttributes().Any(IsUnconditionalRequired), position, propertyIgnoreCase, property.GetAttributes().Any(RequiresValidation), property.GetAttributes().Any(RequiresHookProcessing)));
            }
            return plans;
        }

        private static List<ActionPlan> BuildActionPlans(INamedTypeSymbol type)
        {
            var plans = new List<ActionPlan>();
            foreach (var method in GetPublicMethods(type).Where(method => GetInheritedAttributes(method).Any(IsArgActionMethod)))
            {
                var typeIgnoreCase = GetIgnoreCase(GetInheritedAttributes(method.ContainingType), true);
                var shortcutAttributes = GetInheritedAttributes(method).Where(IsArgShortcut).ToList();
                var includeMethodName = shortcutAttributes.Any(IsShortcutsOnly) == false;
                var aliases = new List<string>();
                if (includeMethodName) aliases.Add(method.Name);
                foreach (var shortcutAttribute in shortcutAttributes)
                {
                    var shortcut = GetShortcutValue(shortcutAttribute);
                    if (shortcut != null) aliases.Add(shortcut);
                }
                var argumentProperties = new List<ArgumentPlan>();
                var parameterArguments = new List<ActionParameterPlan>();
                var usesArgumentModel = method.Parameters.Length == 1 && IsDirectType(method.Parameters[0].Type) == false;
                if (usesArgumentModel)
                {
                    var argumentType = (INamedTypeSymbol)method.Parameters[0].Type;
                    argumentProperties = BuildArgumentPlans(argumentType, GetActionArgumentProperties(argumentType));
                }
                else
                {
                    for (var parameterIndex = 0; parameterIndex < method.Parameters.Length; parameterIndex++)
                    {
                        var parameter = method.Parameters[parameterIndex];
                        var parameterAliases = new List<string> { parameter.Name };
                        foreach (var shortcutAttribute in parameter.GetAttributes().Where(IsArgShortcut))
                        {
                            var shortcut = NormalizeShortcut(GetShortcutValue(shortcutAttribute));
                            if (shortcut != null) parameterAliases.Add(shortcut);
                        }
                        parameterArguments.Add(new ActionParameterPlan(parameter, parameterAliases, parameter.GetAttributes().Any(IsUnconditionalRequired), parameterIndex + 1, GetIgnoreCase(parameter.GetAttributes(), typeIgnoreCase), parameter.GetAttributes().Any(RequiresValidation), parameter.GetAttributes().Any(RequiresHookProcessing)));
                    }
                }
                plans.Add(new ActionPlan(method, aliases, includeMethodName, GetIgnoreCase(GetInheritedAttributes(method), typeIgnoreCase), usesArgumentModel, argumentProperties, parameterArguments));
            }
            return plans;
        }

        private static bool GetIgnoreCase(IEnumerable<AttributeData> attributes, bool defaultValue)
        {
            foreach (var attribute in attributes)
            {
                if (attribute.AttributeClass?.Name == "ArgEnforceCase") return false;
                if (attribute.AttributeClass?.Name != "ArgIgnoreCase") continue;
                if (attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is bool value && value == false) return false;
            }
            return defaultValue;
        }

        private static bool IsArgShortcut(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgShortcut" && IsPowerArgsAttribute(attribute);
        private static bool IsArgPosition(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgPosition" && IsPowerArgsAttribute(attribute);
        private static bool IsArgRange(AttributeData attribute) => attribute.AttributeClass?.Name == "ArgRange" && IsPowerArgsAttribute(attribute);

        private static bool RequiresValidation(AttributeData attribute)
        {
            if (IsArgRequired(attribute) && attribute.NamedArguments.Length == 0 && attribute.ConstructorArguments.Length == 0) return false;
            return IsDerivedFrom(attribute.AttributeClass, "PowerArgs.ArgValidator");
        }

        private static bool RequiresHookProcessing(AttributeData attribute) => attribute.AttributeClass?.Name == "HelpHook" && IsPowerArgsAttribute(attribute);

        private static bool IsShortcutsOnly(AttributeData attribute)
        {
            if (attribute.ConstructorArguments.Length == 0 || attribute.ConstructorArguments[0].Type?.TypeKind != TypeKind.Enum) return false;
            return Convert.ToInt32(attribute.ConstructorArguments[0].Value, System.Globalization.CultureInfo.InvariantCulture) == 2;
        }

        private static string? GetShortcutValue(AttributeData attribute)
        {
            if (attribute.ConstructorArguments.Length == 0 || attribute.ConstructorArguments[0].Value is string == false) return null;
            return (string)attribute.ConstructorArguments[0].Value!;
        }

        private static string? NormalizeShortcut(string? shortcut)
        {
            if (shortcut == null || shortcut.Length == 0) return shortcut;
            return shortcut[0] == '-' || shortcut[0] == '/' ? shortcut.Substring(1) : shortcut;
        }

