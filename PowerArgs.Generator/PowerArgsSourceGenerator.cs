        private static bool IsDirectType(ITypeSymbol type)
        {
            if (type.TypeKind == TypeKind.Enum) return true;
            if (type.SpecialType == SpecialType.System_String || type.SpecialType == SpecialType.System_Boolean || type.SpecialType == SpecialType.System_Byte || type.SpecialType == SpecialType.System_Int32 || type.SpecialType == SpecialType.System_Int64 || type.SpecialType == SpecialType.System_Single || type.SpecialType == SpecialType.System_Double || type.SpecialType == SpecialType.System_DateTime) return true;
            var name = type.ToDisplayString();
            return name == "System.Guid" || name == "System.Uri" || name == "System.Net.IPAddress" || name == "PowerArgs.ConsoleString";
        }

        private static string GenerateAttribute(AttributeData attribute)
        {
            var typeName = attribute.AttributeClass!.ToDisplayString(TypeFormat);
            var constructorArguments = string.Join(", ", attribute.ConstructorArguments.Select(FormatConstant));
            var construction = "new " + typeName + "(" + constructorArguments + ")";
            if (attribute.NamedArguments.Length == 0) return construction;
            return construction + " { " + string.Join(", ", attribute.NamedArguments.Select(argument => Escape(argument.Key) + " = " + FormatConstant(argument.Value))) + " }";
        }

        private static string FormatConstant(TypedConstant constant)
        {
            if (constant.IsNull) return "null";
            if (constant.Kind == TypedConstantKind.Type) return "typeof(" + ((ITypeSymbol)constant.Value!).ToDisplayString(TypeFormat) + ")";
            if (constant.Value is string text) return ToLiteral(text);
            if (constant.Value is char character) return SymbolDisplay.FormatLiteral(character, true);
            if (constant.Value is bool boolean) return boolean ? "true" : "false";
            if (constant.Type?.TypeKind == TypeKind.Enum) return "(" + constant.Type.ToDisplayString(TypeFormat) + ")" + Convert.ToString(constant.Value, System.Globalization.CultureInfo.InvariantCulture);
            return Convert.ToString(constant.Value, System.Globalization.CultureInfo.InvariantCulture) ?? "null";
        }

        private static string? FindShortcut(string name, List<string> excluded)
        {
            var shortcut = string.Empty;
            for (var i = 0; i < name.Length - 1; i++)
            {
                shortcut += name[i];
                if (excluded.Contains(shortcut, StringComparer.OrdinalIgnoreCase) == false) return shortcut;
            }
            return null;
        }

        private static string GetAccessibility(Accessibility accessibility)
        {
            if (accessibility == Accessibility.Public) return "public";
            if (accessibility == Accessibility.Internal) return "internal";
            if (accessibility == Accessibility.Private) return "private";
            if (accessibility == Accessibility.Protected) return "protected";
            if (accessibility == Accessibility.ProtectedOrInternal) return "protected internal";
            if (accessibility == Accessibility.ProtectedAndInternal) return "private protected";
            return "internal";
        }

        private static string Escape(string identifier) => SyntaxFacts.GetKeywordKind(identifier) == SyntaxKind.None ? identifier : "@" + identifier;

        private static string ToLiteral(string value) => SymbolDisplay.FormatLiteral(value, true);

        private static string MakeHintName(INamedTypeSymbol type)
        {
            var name = type.ToDisplayString().Replace('<', '_').Replace('>', '_').Replace('.', '_').Replace('+', '_');
            return name + ".PowerArgs.g.cs";
        }
