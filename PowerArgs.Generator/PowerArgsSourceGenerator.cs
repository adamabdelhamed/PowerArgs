        private static bool IsDirectType(ITypeSymbol type)
        {
            var elementType = GetCollectionElementType(type);
            return elementType != null ? IsDirectScalarType(elementType) : IsDirectScalarType(type);
        }

        private static ITypeSymbol? GetCollectionElementType(ITypeSymbol type)
        {
            if (type is IArrayTypeSymbol array && array.Rank == 1) return array.ElementType;
            if (type is INamedTypeSymbol named && named.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.List<T>") return named.TypeArguments[0];
            return null;
        }

        private static bool CanUseDirectArgument(ITypeSymbol type, ImmutableArray<AttributeData> attributes)
        {
            if (IsDirectType(type) == false || HasDirectRequiredMetadata(attributes) == false) return false;
            if (attributes.Any(attribute => IsArgumentMetadata(attribute) && IsSupportedDirectPropertyAttribute(attribute) == false)) return false;
            // Only exact built-ins have a known raw-value contract for collection validation.
            return GetCollectionElementType(type) == null || attributes.All(attribute => (!RequiresValidation(attribute) || IsBuiltinValidator(attribute)) && !RequiresHookProcessing(attribute));
        }

        private static void AppendArgumentFeatures(StringBuilder source, ITypeSymbol type, ImmutableArray<AttributeData> attributes)
        {
            var elementType = GetCollectionElementType(type);
            var postValidation = attributes.Any(RequiresPostValidation);
            if (elementType == null && !postValidation) return;
            source.Append(" { ");
            if (elementType != null)
            {
                source.Append("CollectionReviver = global::PowerArgs.GeneratedCollectionParser.")
                    .Append(type is IArrayTypeSymbol ? "ReviveArray" : "ReviveList")
                    .Append('<').Append(elementType.ToDisplayString(TypeFormat)).Append(">, ");
            }
            if (postValidation) source.Append("RequiresPostValidation = true");
            source.Append(" }");
        }

        private static bool IsDirectScalarType(ITypeSymbol type)
        {
            if (type is INamedTypeSymbol nullable && nullable.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T) return IsDirectScalarType(nullable.TypeArguments[0]);
            if (type.TypeKind == TypeKind.Enum) return true;
            // These use the classic conversion service, preserving culture, custom revivers and errors.
            if (type.SpecialType == SpecialType.System_Char || type.SpecialType == SpecialType.System_Decimal || type.SpecialType == SpecialType.System_SByte || type.SpecialType == SpecialType.System_Int16 || type.SpecialType == SpecialType.System_UInt16 || type.SpecialType == SpecialType.System_UInt32 || type.SpecialType == SpecialType.System_UInt64) return true;
            if (type.SpecialType == SpecialType.System_String || type.SpecialType == SpecialType.System_Boolean || type.SpecialType == SpecialType.System_Byte || type.SpecialType == SpecialType.System_Int32 || type.SpecialType == SpecialType.System_Int64 || type.SpecialType == SpecialType.System_Single || type.SpecialType == SpecialType.System_Double || type.SpecialType == SpecialType.System_DateTime) return true;
            var name = type.ToDisplayString();
            return name == "System.Guid" || name == "System.Uri" || name == "System.Net.IPAddress" || name == "PowerArgs.ConsoleString";
        }

        private static string GenerateAttribute(AttributeData attribute)
        {
            var typeName = attribute.AttributeClass!.ToDisplayString(TypeFormat);
            var constructorArguments = string.Join(", ", attribute.ConstructorArguments.Select(FormatConstant));
            var construction = "new " + typeName + "(" + constructorArguments + ")";
            if (attribute.NamedArguments.Length == 0) return construction;
            return construction + " { " + string.Join(", ", attribute.NamedArguments.Select(argument => Escape(argument.Key) + " = " + FormatConstant(argument.Value))) + " }";
        }

        private static string FormatConstant(TypedConstant constant)
        {
            if (constant.IsNull) return "null";
            if (constant.Kind == TypedConstantKind.Array)
            {
                var elementType = ((IArrayTypeSymbol)constant.Type!).ElementType.ToDisplayString(TypeFormat);
                return "new " + elementType + "[] { " + string.Join(", ", constant.Values.Select(FormatConstant)) + " }";
            }
            if (constant.Kind == TypedConstantKind.Type) return "typeof(" + ((ITypeSymbol)constant.Value!).ToDisplayString(RuntimeTypeFormat) + ")";
            if (constant.Value is string text) return ToLiteral(text);
            if (constant.Value is char character) return SymbolDisplay.FormatLiteral(character, true);
            if (constant.Value is bool boolean) return boolean ? "true" : "false";
            if (constant.Type?.TypeKind == TypeKind.Enum) return "(" + constant.Type.ToDisplayString(TypeFormat) + ")" + Convert.ToString(constant.Value, System.Globalization.CultureInfo.InvariantCulture);
            return Convert.ToString(constant.Value, System.Globalization.CultureInfo.InvariantCulture) ?? "null";
        }

        private static bool CanGenerateAttribute(AttributeData attribute)
        {
            if (attribute.AttributeClass == null || attribute.AttributeConstructor == null) return false;
            if (attribute.AttributeConstructor.DeclaredAccessibility != Accessibility.Public && attribute.AttributeConstructor.DeclaredAccessibility != Accessibility.Internal) return false;
            return attribute.ConstructorArguments.All(CanGenerateConstant) && attribute.NamedArguments.All(argument => CanGenerateConstant(argument.Value));
        }

        private static bool CanGenerateConstant(TypedConstant constant)
        {
            if (constant.Kind == TypedConstantKind.Error) return false;
            return constant.Kind != TypedConstantKind.Array || constant.Values.All(CanGenerateConstant);
        }

        private static string? FindShortcut(string name, List<string> excluded)
        {
            var shortcut = string.Empty;
            for (var i = 0; i < name.Length - 1; i++)
            {
                shortcut += name[i];
                if (excluded.Contains(shortcut, StringComparer.OrdinalIgnoreCase) == false) return shortcut;
            }
            return null;
        }

        private static string GetAccessibility(Accessibility accessibility)
        {
            if (accessibility == Accessibility.Public) return "public";
            if (accessibility == Accessibility.Internal) return "internal";
            if (accessibility == Accessibility.Private) return "private";
            if (accessibility == Accessibility.Protected) return "protected";
            if (accessibility == Accessibility.ProtectedOrInternal) return "protected internal";
            if (accessibility == Accessibility.ProtectedAndInternal) return "private protected";
            return "internal";
        }

        private static string Escape(string identifier) => SyntaxFacts.GetKeywordKind(identifier) == SyntaxKind.None ? identifier : "@" + identifier;

        private static string ToLiteral(string value) => SymbolDisplay.FormatLiteral(value, true);

        private static string MakeHintName(INamedTypeSymbol type)
        {
            var name = type.ToDisplayString().Replace('<', '_').Replace('>', '_').Replace('.', '_').Replace('+', '_');
            return name + ".PowerArgs.g.cs";
        }
